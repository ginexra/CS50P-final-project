import pytest
from project import add_number, hint_generator, count_moves

def test_add_number():
    assert add_number('123') == (1, 2, 3)
    assert add_number('1-2-3') == (1, 2, 3)
    assert add_number('(1, 2) - 3') == (1, 2, 3)
    assert add_number('row: 1, column: 2, guess: 3') == (1, 2, 3)

    with pytest.raises(ValueError):
        add_number('helloo')

